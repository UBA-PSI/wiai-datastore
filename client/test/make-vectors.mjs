const pubOf = (d) => { const e = createECDH('prime256v1'); e.setPrivateKey(d); return new Uint8Array(e.getPublicKey()); };
const kp = async (name) => { const d = await scalar(name); return { d, pub: pubOf(d) }; };
const keyJson = (k) => ({ d: hex(k.d), pub: b64u(k.pub) });

