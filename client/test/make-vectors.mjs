// signature helper: keep an existing valid signature (ECDSA is randomised)
async function sign(key, message, oldSig) {
  if (oldSig && await I.ecdsaVerify(key.pub, I.b64uDecode(oldSig, 64), message)) return oldSig;
  return b64u(await I.ecdsaSign(await I.importPrivate('S', key.d, key.pub), message));
}

