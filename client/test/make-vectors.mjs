// ---- records ----
async function recordVector(name, kind, body, mime, version, nonceStart) {
  const rid = await I.recordId(dk.kId, name);
  const built = I.buildRecordPlaintext(name, kind, body, mime, TIME_MS);
  const nonce = seq(12, nonceStart);
  const env = await I.sealRecord({ kEncRaw: dk.kEnc, epoch: 1, scope: SCOPE, vault: VAULT, rid, version, plaintext: built.plaintext, nonce });
  const aad = I.concat(env.subarray(0, 10), I.aadRecord(SCOPE, VAULT, rid, version));
  return {
    scope: SCOPE, vault: VAULT, name, name_utf8_hex: hex(utf8(name)), record_id: rid, version, epoch: 1, kind, mime: mime || null, time: TIME_MS,
    header: new TextDecoder().decode(built.headerBytes), body_hex: hex(body), plaintext_hex: hex(built.plaintext), plaintext_len: built.plaintext.length,
    aad_hex: hex(aad), nonce_hex: hex(nonce), envelope_hex: hex(env), envelope_len: env.length, commit: await I.commitment(dk.kCommit, rid, version, built.plaintext),
  };
}
